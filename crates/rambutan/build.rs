//! Bakes the per-build policy constants into the loader (plan Task 1.6; spec §3.1).
//!
//! The loader IS policy: its kernel cmdline, initrd digest, and SB requirement are
//! compile-time constants inside the signed PE — never runtime inputs. A loader built
//! without its constants must NOT exist, so an absent env var PANICS the build (fail
//! closed at build time). Dev defaults exist ONLY behind an explicit
//! `RECIPES_LOADER_DEV=1` (zero digest + a marker cmdline) so a bare-checkout
//! `cargo build`/`cargo test` works without the image-builder driving it; the real
//! build (`build_efi_loader`) always sets all three vars.

                                                                                     
                                                                        
include!("src/hex.rs");

use std::{env, fs, path::PathBuf};

fn main() {
                                                                                       
                                                                                  
                                                                                    
                                                                                      
                                                                                      
                                                                                      
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("uefi") {
        println!("cargo:rustc-link-arg-bins=/debug:none");
    }

    println!("cargo:rerun-if-env-changed=RECIPES_LOADER_CMDLINE");
    println!("cargo:rerun-if-env-changed=RECIPES_LOADER_INITRD_SHA256");
    println!("cargo:rerun-if-env-changed=RECIPES_LOADER_SB_REQUIRED");
    println!("cargo:rerun-if-env-changed=RECIPES_LOADER_DEV");

    let dev = env::var("RECIPES_LOADER_DEV").as_deref() == Ok("1");

                                                                                               
                                                                                                            
                                                                                                           
                                                                                                           
                                                                                    
    let cmdline = read_var("RECIPES_LOADER_CMDLINE", dev, "rambutan-dev-unconfigured");
    let sha_hex = read_var("RECIPES_LOADER_INITRD_SHA256", dev, &"0".repeat(64));
    let sb_raw = read_var("RECIPES_LOADER_SB_REQUIRED", dev, "0");

                                                                                        
                                                                       
    if !cmdline.bytes().all(|b| b.is_ascii_graphic() || b == b' ') {
        panic!(
            "RECIPES_LOADER_CMDLINE must be printable ASCII + space only \
             (got a control/non-ASCII byte); refusing to bake a cmdline the \
             loader would reject at boot"
        );
    }

    let digest = decode_hex_32(&sha_hex).unwrap_or_else(|| {
                       
        panic!(
            "RECIPES_LOADER_INITRD_SHA256 must be exactly 64 lowercase hex chars \
             (the pinned hex representation), got {:?}",
            sha_hex
        )
    });

    let sb_required = match sb_raw.as_str() {
        "1" => true,
        "0" => false,
        other => panic!("RECIPES_LOADER_SB_REQUIRED must be \"1\" or \"0\", got {other:?}"),
    };

    let mut digest_literal = String::from("[");
    for (i, b) in digest.iter().enumerate() {
        if i > 0 {
            digest_literal.push_str(", ");
        }
        digest_literal.push_str(&format!("0x{b:02x}"));
    }
    digest_literal.push(']');

    let generated = format!(
        "// generated by build.rs — do not edit\n\
         pub const KERNEL_CMDLINE: &str = {cmdline:?};\n\
         pub const INITRD_SHA256: [u8; 32] = {digest_literal};\n\
         pub const SB_REQUIRED: bool = {sb_required};\n"
    );

    let out = PathBuf::from(env::var("OUT_DIR").expect("cargo always sets OUT_DIR"));
    fs::write(out.join("baked.rs"), generated).expect("write baked.rs");
}

/// Required env var: absent ⇒ panic, unless the explicit dev escape is set.
fn read_var(name: &str, dev: bool, dev_default: &str) -> String {
    match env::var(name) {
        Ok(v) => v,
        Err(_) if dev => dev_default.to_string(),
        Err(_) => panic!(
            "{name} is not set. The loader's constants are baked at build time \
             (fail closed — a loader without its policy must not exist). Either \
             drive the build through the image-builder (which sets RECIPES_LOADER_*) \
             or set RECIPES_LOADER_DEV=1 explicitly for a dev/test build."
        ),
    }
}
